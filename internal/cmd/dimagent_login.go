package cmd

import (
	"context"
	"fmt"

	"github.com/router-for-me/CLIProxyAPI/v7/internal/config"
	sdkAuth "github.com/router-for-me/CLIProxyAPI/v7/sdk/auth"
	log "github.com/sirupsen/logrus"
)

// DoDimAgentLogin triggers the DimAgent OAuth authorization code + PKCE login
// flow and saves the resulting tokens. It starts a local callback server on
// the fixed redirect port (54321), opens the browser to the authorization URL,
// waits for the callback, then exchanges the code for tokens.
func DoDimAgentLogin(cfg *config.Config, options *LoginOptions) {
	if options == nil {
		options = &LoginOptions{}
	}

	manager := newAuthManager()
	authOpts := &sdkAuth.LoginOptions{
		NoBrowser: options.NoBrowser,
		Metadata:  map[string]string{},
		Prompt:    options.Prompt,
	}

	record, savedPath, err := manager.Login(context.Background(), "dimagent", cfg, authOpts)
	if err != nil {
		log.Errorf("DimAgent authentication failed: %v", err)
		return
	}

	if savedPath != "" {
		fmt.Printf("Authentication saved to %s\n", savedPath)
	}
	if record != nil && record.Label != "" {
		fmt.Printf("Authenticated as %s\n", record.Label)
	}
	fmt.Println("You can now use DimAgent services through this CLI")
}
